package org.purpleBean.kmip.model.v2_1.type;

import java.util.Set;
import lombok.Builder;
import lombok.Data;
import lombok.NonNull;
import org.purpleBean.kmip.api.EncodingType;
import org.purpleBean.kmip.api.KmipContext;
import org.purpleBean.kmip.api.KmipDataType;
import org.purpleBean.kmip.api.KmipSpec;
import org.purpleBean.kmip.api.KmipTag;

/**
 * KMIP ClientCorrelationValue dataType.
 */
@Data
@Builder(toBuilder = true)
public class ClientCorrelationValue implements KmipDataType {

  public static final KmipTag kmipTag = KmipTag.Standard.CLIENT_CORRELATION_VALUE.inst();
  public static final EncodingType encodingType = EncodingType.TEXT_STRING;
  private static final Set<KmipSpec> supportedVersions =
      Set.of(KmipSpec.UnknownVersion, KmipSpec.V2_1, KmipSpec.V3_0);
      // introduced in KMIP 2.1 — extend if present in later specs

  static {
    for (KmipSpec spec : supportedVersions) {
      if (spec == KmipSpec.UnknownVersion || spec == KmipSpec.UnsupportedVersion) {
        continue;
      }
      KmipDataType.register(spec, kmipTag.getValue(), encodingType, ClientCorrelationValue.class);
    }
  }

  @NonNull
  private final String value;

  @Builder
  private ClientCorrelationValue(@NonNull String value) {
    this.value = value;
    validate();
  }

  public static ClientCorrelationValue of(@NonNull String value) {
    return new ClientCorrelationValue(value);
  }

  private void validate() {
    if (!isSupported()) {
      throw new IllegalArgumentException(
          String.format("Unsupported object type for %s: %s", KmipContext.getSpec(), getKmipTag()));
    }
    // No validation needed for this structure
  }

  @Override
  public KmipTag getKmipTag() {
    return kmipTag;
  }

  @Override
  public EncodingType getEncodingType() {
    return encodingType;
  }

  @Override
  public boolean isSupported() {
    KmipSpec spec = KmipContext.getSpec();
    return supportedVersions.contains(spec);
  }
}