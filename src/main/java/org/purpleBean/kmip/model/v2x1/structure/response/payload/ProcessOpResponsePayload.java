package org.purpleBean.kmip.model.v2x1.structure.response.payload;

import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import lombok.Builder;
import lombok.Data;
import lombok.NonNull;
import org.purpleBean.kmip.api.EncodingType;
import org.purpleBean.kmip.api.KmipContext;
import org.purpleBean.kmip.api.KmipDataType;
import org.purpleBean.kmip.api.KmipSpec;
import org.purpleBean.kmip.api.KmipTag;
import org.purpleBean.kmip.api.response.ResponsePayloadStructure;
import org.purpleBean.kmip.model.core.enumeration.Operation;
import org.purpleBean.kmip.model.core.type.AsynchronousCorrelationValue;

@Data
@Builder(toBuilder = true)
public class ProcessOpResponsePayload implements ResponsePayloadStructure {

  private static final Operation.Value operation = Operation.Standard.PROCESS;
  private static final Set<KmipSpec> supportedVersions =
      Set.of(KmipSpec.UnknownVersion, KmipSpec.V2_1, KmipSpec.V3_0);

  static {
    for (KmipSpec spec : supportedVersions) {
      if (spec == KmipSpec.UnknownVersion || spec == KmipSpec.UnsupportedVersion) {
        continue;
      }
      KmipDataType.register(spec, kmipTag.getValue(), encodingType, ProcessOpResponsePayload.class);
      ResponsePayloadStructure.register(spec, operation, ProcessOpResponsePayload.class,
          ProcessOpResponsePayload::of);
    }
  }

  @NonNull
  private final AsynchronousCorrelationValue asynchronousCorrelationValue;

  @Builder
  private ProcessOpResponsePayload(
      @NonNull AsynchronousCorrelationValue asynchronousCorrelationValue) {
    this.asynchronousCorrelationValue = asynchronousCorrelationValue;
    validate();
  }

  public static ProcessOpResponsePayload of(List<KmipDataType> values) {
    Map<KmipTag, List<KmipDataType>> map = values
        .stream()
        .collect(Collectors.groupingBy(KmipDataType::getKmipTag));
    return ProcessOpResponsePayload
        .builder()
        .asynchronousCorrelationValue((AsynchronousCorrelationValue) map
            .get(AsynchronousCorrelationValue.kmipTag)
            .getFirst())
        .build();
  }

  private void validate() {
    if (!isSupported()) {
      throw new IllegalArgumentException(
          String.format("Unsupported object type for %s: %s", KmipContext.getSpec(), getKmipTag()));
    }
  }

  @Override
  public KmipTag getKmipTag() {
    return kmipTag;
  }

  @Override
  public EncodingType getEncodingType() {
    return encodingType;
  }

  @Override
  public boolean isSupported() {
    KmipSpec spec = KmipContext.getSpec();
    return supportedVersions.contains(spec) && Stream
        .of(getValue())
        .allMatch(KmipDataType::isSupported);
  }

  @Override
  public KmipDataType[] getValue() {
    return Stream
        .of(asynchronousCorrelationValue)
        .filter(Objects::nonNull)
        .map(KmipDataType.class::cast)
        .toArray(KmipDataType[]::new);
  }

  @Override
  public Operation getCorrespondingOperation() {
    return operation.inst();
  }
}
